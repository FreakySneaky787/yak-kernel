//! ulib: the tiny runtime of KernelTry user programs.
//!
//! - `_start`: the entry point the kernel jumps to. RDI/RSI hold pointer and
//!   length of the argument block (arguments separated by NUL bytes); it calls
//!   the program's `main(Args)` (declared with `ulib::entry!`) and passes its
//!   result to `exit`.
//! - `sys`: the raw system calls.
//! - `print!` / `println!` (stdout), `eprintln!` (stderr), `io::read_line`.
//! - `fs`: files and directories (`File`, `Dir`, `stat`, `cwd`).
//! - `heap`: the `#[global_allocator]` – programs can use `alloc` (`Vec`, `String`, ...).
//! - `process`: start child programs, wait for them, kill them.
//! - `dns`: name -> IPv4 address.
//! - A panic handler that prints the message and exits with code 101.

#![no_std]

